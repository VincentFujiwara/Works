//Дан размер файла в байтах. Используя операцию деления нацело,
//найти количество полных килобайтов, которые занимает данный файл
//(1 килобайт = 1024 байта).
// 
// Решение Урсу Артёма


#include <stdio.h>
int main (){
	int kb,b;
	scanf ("%d",&b);
	kb = b / 1024;
	printf ("%d\n",kb);
	return 0;
}
