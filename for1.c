//Даны целые числа K и N (N > 0). Вывести N раз число K.
// 
// Решение Урсу Артёма

#include <stdio.h>
int main (){
	int N,K; //вводим по условию переменые н и к
	scanf ("%d %d",&K,&N); // просто сканф ничего более
	for (int i = N; i>0; i--){ //цикл - сначала индет старт,сколько,счет.После этого всего тело цикла.
		printf ("%d\n",K);
	}
	return 0;//трасировочной таблички не требует.
}
