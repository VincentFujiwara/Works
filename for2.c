// Задачник Абрамяна - задача for2
//
//Даны два целых числа A и B (A < B). Вывести в порядке возрастания все
//целые числа, расположенные между A и B (включая сами числа A и B), а
//также количество N этих чисел.
// 
// Решение Урсу Артёма
//

#include <stdio.h>
int main (){
	int a,b,n;
	n = 0;
	scanf ("%d %d",&a,&b);
	if (a >= b) {
		printf ("input error!");
		return 1;
	}
	for (int i = a; i <= b; i++) {
		printf ("%d\n",i);
		n++;
	}
	printf ("%d",n);
	return 0;//трасировочной таблички не требует.
}
